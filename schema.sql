-- Audit events are visible only to staff accounts.
drop policy if exists hcs_events_staff_read on public.hcs_events;
create policy hcs_events_staff_read on public.hcs_events for select to authenticated using (true);

revoke insert, update, delete, truncate, references, trigger on public.hcs_projects, public.hcs_cycles, public.hcs_beds, public.hcs_events from anon, authenticated;
grant select on public.hcs_projects, public.hcs_cycles, public.hcs_beds to anon, authenticated;
grant select on public.hcs_events to authenticated;

create or replace function public.hcs_add_project(p_code text, p_name text)
returns public.hcs_projects
language plpgsql security definer set search_path = ''
as $$
declare v_project public.hcs_projects;
begin
  if (select auth.uid()) is null then
    raise exception 'Supervisor login required.' using errcode = '42501';
  end if;
  p_code := pg_catalog.btrim(p_code);
  p_name := pg_catalog.btrim(p_name);
  if p_code is null or p_code !~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,19}$' then
    raise exception 'Project code must have 1-20 letters/numbers, underscore or hyphen.';
  end if;
  if p_name is null or pg_catalog.char_length(p_name) not between 2 and 100 then
    raise exception 'Project name must have 2-100 characters.';
  end if;
  insert into public.hcs_projects(code, name) values (p_code, p_name)
  returning * into v_project;
  return v_project;
end;
$$;

create or replace function public.hcs_apply_action(
  p_bed_no integer,
  p_action text,
  p_at timestamptz default now(),
  p_project_id bigint default null,
  p_height_mm numeric default null,
  p_strand_pattern text default null,
  p_cube_strength_mpa numeric default null
)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_bed public.hcs_beds;
  v_cycle public.hcs_cycles;
  v_project public.hcs_projects;
  v_id uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'Supervisor login required.' using errcode = '42501';
  end if;
  if p_at is null or p_at > now() + interval '1 minute' or p_at < '2020-01-01'::timestamptz then
    raise exception 'Select a valid event time (not in the future).';
  end if;
  select * into v_bed from public.hcs_beds where bed_no = p_bed_no for update;
  if not found then raise exception 'Bed % not found.', p_bed_no; end if;

  if p_action = 'start_preparation' then
    if v_bed.status <> 'available' then raise exception 'Bed is busy; refresh the dashboard.'; end if;
    select * into v_project from public.hcs_projects where id = p_project_id and is_active = true;
    if not found then raise exception 'Select a valid active project.'; end if;
    if p_height_mm is null or p_height_mm <= 0 or p_height_mm > 1000 then
      raise exception 'Height must be between 0 and 1000 mm.';
    end if;
    if p_strand_pattern is null or pg_catalog.char_length(pg_catalog.btrim(p_strand_pattern)) not between 1 and 150 then
      raise exception 'Enter a strand pattern (1-150 characters).';
    end if;
    insert into public.hcs_cycles (
      bed_no, project_id, project_code, project_name, height_mm, strand_pattern, prep_start
    ) values (
      p_bed_no, v_project.id, v_project.code, v_project.name, p_height_mm,
      pg_catalog.btrim(p_strand_pattern), p_at
    ) returning id into v_id;
    update public.hcs_beds set status = 'preparation', active_cycle_id = v_id, updated_at = now()
    where bed_no = p_bed_no;

  else
    if v_bed.status = 'available' or v_bed.active_cycle_id is null then
      raise exception 'This bed has no active production cycle.';
    end if;
    select * into v_cycle from public.hcs_cycles where id = v_bed.active_cycle_id for update;
    if not found then raise exception 'Active production record not found.'; end if;
    v_id := v_cycle.id;

    case p_action
      when 'finish_preparation' then
        if v_bed.status <> 'preparation' then raise exception 'Bed is not in Preparation.'; end if;
        if p_at < v_cycle.prep_start then raise exception 'Time is earlier than Preparation start.'; end if;
        update public.hcs_cycles set prep_end = p_at where id = v_id;
        update public.hcs_beds set status = 'ready_casting', updated_at = now() where bed_no = p_bed_no;

      when 'start_casting' then
        if v_bed.status <> 'ready_casting' then raise exception 'Finish Preparation first.'; end if;
        if p_at < v_cycle.prep_end then raise exception 'Time is earlier than Preparation end.'; end if;
        update public.hcs_cycles set casting_start = p_at where id = v_id;
        update public.hcs_beds set status = 'casting', updated_at = now() where bed_no = p_bed_no;

      when 'finish_casting' then
        if v_bed.status <> 'casting' then raise exception 'Bed is not in Casting.'; end if;
        if p_at < v_cycle.casting_start then raise exception 'Time is earlier than Casting start.'; end if;
        -- Automatic curing start = casting completion instant.
        update public.hcs_cycles set casting_end = p_at, curing_start = p_at where id = v_id;
        update public.hcs_beds set status = 'curing', updated_at = now() where bed_no = p_bed_no;

      when 'set_cube_strength' then
        if v_bed.status <> 'curing' then raise exception 'Cube strength can only be updated during Curing.'; end if;
        if p_at < coalesce(v_cycle.cube_strength_updated_at, v_cycle.curing_start) then raise exception 'Time is earlier than Curing start or previous cube strength update.'; end if;
        if p_cube_strength_mpa is null or p_cube_strength_mpa <= 0 or p_cube_strength_mpa > 250 then
          raise exception 'Cube strength must be >0 and <=250 MPa.';
        end if;
        update public.hcs_cycles
        set cube_strength_mpa = p_cube_strength_mpa, cube_strength_updated_at = p_at where id = v_id;

      when 'start_cut' then
        if v_bed.status <> 'curing' then raise exception 'Bed is not in Curing.'; end if;
        if p_at < coalesce(v_cycle.cube_strength_updated_at, v_cycle.curing_start) then raise exception 'Cut cannot start before the recorded cube strength update.'; end if;
        if v_cycle.cube_strength_mpa is null then raise exception 'Enter cube strength before cut & demoulding.'; end if;
        update public.hcs_cycles set cut_start = p_at where id = v_id;
        update public.hcs_beds set status = 'cutting', updated_at = now() where bed_no = p_bed_no;

      when 'finish_cut' then
        if v_bed.status <> 'cutting' then raise exception 'Bed is not in Cut & Demoulding.'; end if;
        if p_at < v_cycle.cut_start then raise exception 'Time is earlier than Cut & Demoulding start.'; end if;
        update public.hcs_cycles set cut_end = p_at where id = v_id;
        -- The finished cycle remains in hcs_cycles as archive; only bed is released.
        update public.hcs_beds set status = 'available', active_cycle_id = null, updated_at = now()
        where bed_no = p_bed_no;

      else raise exception 'Unsupported action.';
    end case;
  end if;

  insert into public.hcs_events(cycle_id, bed_no, action, event_at, strength_mpa)
  values (v_id, p_bed_no, p_action, p_at,
    case when p_action = 'set_cube_strength' then p_cube_strength_mpa else null end);

  return pg_catalog.jsonb_build_object('ok', true, 'bed_no', p_bed_no, 'action', p_action, 'cycle_id', v_id);
end;
$$;

