-- Restrictive table policies: anonymous and signed-in viewers may read;
-- direct mutations are blocked, to enforce transactional transitions below.
alter table public.hcs_projects enable row level security;
alter table public.hcs_cycles enable row level security;
alter table public.hcs_beds enable row level security;
alter table public.hcs_events enable row level security;

drop policy if exists hcs_projects_read on public.hcs_projects;
create policy hcs_projects_read on public.hcs_projects for select to anon, authenticated using (true);
drop policy if exists hcs_cycles_read on public.hcs_cycles;
create policy hcs_cycles_read on public.hcs_cycles for select to anon, authenticated using (true);
drop policy if exists hcs_beds_read on public.hcs_beds;
