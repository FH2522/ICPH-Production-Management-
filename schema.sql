-- ICPH HCS Production Control - run ONCE in Supabase SQL Editor.
-- Public may VIEW production data. Only Auth users can change it via RPC.
-- Do NOT expose the service_role key or enable direct client table writes.

create extension if not exists pgcrypto;

create table if not exists public.hcs_projects (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Za-z0-9][A-Za-z0-9_-]{0,19}$'),
  name text not null check (char_length(trim(name)) between 2 and 100),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.hcs_cycles (
  id uuid primary key default gen_random_uuid(),
  bed_no smallint not null check (bed_no between 1 and 5),
  project_id bigint not null references public.hcs_projects(id),
  project_code text not null,
  project_name text not null,
  height_mm numeric(6,1) not null check (height_mm > 0 and height_mm <= 1000),
  strand_pattern text not null check (char_length(trim(strand_pattern)) between 1 and 150),
  prep_start timestamptz not null,
  prep_end timestamptz,
  casting_start timestamptz,
  casting_end timestamptz,
  curing_start timestamptz,
  cut_start timestamptz,
  cut_end timestamptz,
  cube_strength_mpa numeric(6,2) check (cube_strength_mpa > 0 and cube_strength_mpa <= 250),
  cube_strength_updated_at timestamptz,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  constraint hcs_prep_order check (prep_end is null or prep_end >= prep_start),
  constraint hcs_cast_order check (casting_start is null or (prep_end is not null and casting_start >= prep_end)),
  constraint hcs_cast_end_order check (casting_end is null or (casting_start is not null and casting_end >= casting_start)),
  constraint hcs_cure_order check (curing_start is null or (casting_end is not null and curing_start = casting_end)),
  constraint hcs_cut_order check (cut_start is null or (curing_start is not null and cut_start >= curing_start)),
  constraint hcs_cut_end_order check (cut_end is null or (cut_start is not null and cut_end >= cut_start))
);

-- Prevent double-booked ongoing batches even under simultaneous requests.
create unique index if not exists one_active_cycle_per_hcs_bed
on public.hcs_cycles(bed_no) where cut_end is null;
create index if not exists hcs_cycle_casting_index on public.hcs_cycles(casting_start desc);
create index if not exists hcs_cycle_archive_index on public.hcs_cycles(cut_end desc);

create table if not exists public.hcs_beds (
  bed_no smallint primary key check (bed_no between 1 and 5),
  status text not null default 'available' check (status in (
    'available', 'preparation', 'ready_casting', 'casting', 'curing', 'cutting'
  )),
  active_cycle_id uuid references public.hcs_cycles(id),
  updated_at timestamptz not null default now(),
  constraint available_has_no_cycle check (
    (status = 'available' and active_cycle_id is null) or
    (status <> 'available' and active_cycle_id is not null)
  )
);

create table if not exists public.hcs_events (
  id bigint generated by default as identity primary key,
  cycle_id uuid not null references public.hcs_cycles(id) on delete cascade,
  bed_no smallint not null,
  action text not null,
  event_at timestamptz not null,
  entered_at timestamptz not null default now(),
  operator_id uuid default auth.uid(),
  strength_mpa numeric(6,2)
);
create index if not exists hcs_events_cycle_index on public.hcs_events(cycle_id, event_at);

